def woven_theory_markdown() -> str:
    lines = [
        "# Часть III. Связная теория понятий",
        "",
        "В этой части термины не идут как мастерские или практические задания. Они вплетены в теоретические тома. Каждый том показывает, как понятия работают вместе и почему одно понятие нельзя понимать без соседних.",
        "",
    ]
    chapter_no = 0
    seen_terms: set[str] = set()
    for track_no, (title, description, terms, artifacts) in enumerate(list(TRACKS) + ADDITIONAL_TRACKS, start=1):
        lines.extend([
            f"## Том {track_no}. {title}",
            "",
            description,
            "",
            "Главная мысль тома: фундамент появляется не из списка слов, а из связей. Ниже каждое понятие раскрывается через слой существования, низкий механизм и соседние понятия.",
            "",
        ])
        for topic_no, term in enumerate(terms, start=1):
            chapter_no += 1
            term_key = term.casefold()
            if term_key in seen_terms:
                lines.extend([
                    f"### Повторная связка {chapter_no}. {term}",
                    "",
                    f"`{term}` уже разобран раньше как самостоятельное понятие. В этом томе он нужен не как новая глава, а как мост к контексту `{title}`: тот же термин переносится в другую среду, где меняются соседние понятия, источники правил и способы проверки.",
                    "",
                ])
                continue
            seen_terms.add(term_key)
            artifact = artifact_for(term, artifacts, topic_no)
            lines.extend([f"### Понятие {chapter_no}. {term}", ""])
            lines.extend(term_theory_paragraphs(term, title, artifact, chapter_no))
            lines.append("")
        lines.extend([
            f"### Системная связка тома {track_no}",
            "",
            f"Понятия этого тома нельзя читать отдельно. Они образуют одну модель: {', '.join(terms)}. "
            "Хорошее понимание появляется, когда читатель может объяснить, какой слой задает правило, "
            "какой механизм исполняет это правило и какой соседний термин меняет интерпретацию. "
            "Так теория становится широкой, но не распадается на словарь.",
            "",
        ])
    return "\n".join(lines) + "\n"


def theoretical_sources_note_markdown() -> str:
    return dedent(
        """
        # Как проверять теорию по документации

        Официальная документация в этой книге нужна не как украшение. Она задает
        правила: формат PE, ABI Windows x64, ELF gABI, DWARF, Arm/RISC-V ISA,
        UEFI, Android runtime, JVM, .NET, OpenOCD, QEMU, YARA, Frida и другие.
        Но документация сама по себе не делает вывод за исследователя. Она
        отвечает на вопрос "как устроено правило". Бинарный объект отвечает на
        вопрос "что мы наблюдаем". Теория связывает первое со вторым.

        Если в тексте написано `RVA`, проверять нужно не перевод слова, а
        отношение RVA к ImageBase, section table и file offset. Если написано
        `ABI`, проверять нужно регистры аргументов, сохранение регистров, стек и
        возвращаемое значение. Если написано `MMIO`, проверять нужно memory map,
        base address периферии, register offset, bit field и side effects.

        Такая проверка не превращает книгу в практикум. Это часть теории:
        научная фраза должна быть связана с правилом, иначе она остается
        красивым словом.
        """
    ).strip() + "\n"


