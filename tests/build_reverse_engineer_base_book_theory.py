def remove_practical_base_chapters(text: str) -> str:
    text = re.sub(r"\n### Мини-практика\n.*?(?=\n## |\n### |\Z)", "\n", text, flags=re.S)
    parts = text.split("\n## ")
    if not parts:
        return text
    kept = [parts[0]]
    dropped_prefixes = (
        "Глава 25. Первый час",
        "Глава 26. Как не утонуть",
        "Глава 27. От байтов к отчету",
        "Глава 28. Два сквозных примера",
        "Глава 29. Лабораторные работы",
    )
    for part in parts[1:]:
        heading = part.splitlines()[0].strip()
        if heading.startswith(dropped_prefixes):
            continue
        kept.append("## " + part)
    return "\n".join(kept)


