def qa_no_duplicate_long_paragraphs(text: str) -> None:
    paragraphs = [
        " ".join(p.split())
        for p in text.split("\n\n")
        if len(" ".join(p.split())) > 220 and not p.lstrip().startswith("|")
    ]
    duplicates = [item for item, count in Counter(paragraphs).items() if count > 1]
    if duplicates:
        sample = duplicates[0][:180]
        raise RuntimeError(f"Duplicate long paragraph detected: {sample!r}")


