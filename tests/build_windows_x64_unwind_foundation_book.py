    """
    Поиск обработчика можно представить как подъем по лестнице вызовов. Внизу
    лестницы находится функция, где исключение произошло. Выше - функция,
    которая ее вызвала. Еще выше - следующая. Windows идет от нижнего кадра к
    верхнему и на каждом шаге спрашивает: у этого кадра есть обработчик,
    подходящий для данного исключения?

    На x64 для текущего `RIP` сначала нужно найти запись функции. Это делает
    механизм function table lookup: по адресу управления ищется
    `RUNTIME_FUNCTION`, диапазон которого содержит этот адрес. Запись дает
    ссылку на `UNWIND_INFO`. В `UNWIND_INFO` указано, как откатить эффекты
    prolog и есть ли хвост с handler-данными.

    Если у функции есть language-specific handler, Windows вызывает его не как
    обычную пользовательскую функцию "наугад", а по договору runtime. Handler
    получает описание исключения, establisher frame, context и dispatcher
    context. Он может сказать: "я обработаю", "продолжайте поиск" или "нужно
    выполнить unwind".

    Если текущий frame не содержит подходящего обработчика, Windows выполняет
    virtual unwind: не меняет настоящий стек немедленно, а вычисляет, каким был
    бы context caller-а. После этого повторяет поиск уже для caller frame.

    Поэтому связь такая:

    ```text
    исключение -> текущий RIP -> RUNTIME_FUNCTION -> UNWIND_INFO ->
    virtual unwind -> caller RIP/RSP -> следующий RUNTIME_FUNCTION
    ```

    Твой анализатор занимается статической частью этой цепочки. Он не
    заменяет Windows dispatcher, но проверяет таблицы и unwind-описания,
    которые dispatcher использует. Если эти данные повреждены, противоречивы
    или размещены странно, stack walk, отладка, crash dump analysis и ручной
    reverse engineering могут стать намного сложнее.
    """,
