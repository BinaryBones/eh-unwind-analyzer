def clean(text: str) -> str:
    return dedent(text).strip() + "\n"


def section(number: str, title: str, body: str) -> str:
    extra = SECTION_EXPANSIONS.get(number, "")
    if extra:
        return f"## {number}. {title}\n\n{clean(body)}\n{clean(extra)}\n"
    return f"## {number}. {title}\n\n{clean(body)}\n"


def include_deep_dive(title: str, rel_path: str, note: str) -> str:
    source = ROOT / rel_path
    text = source.read_text(encoding="utf-8")
    converted: list[str] = []
    for line in text.splitlines():
        if line.startswith("### "):
            converted.append("### " + line[4:])
        elif line.startswith("## "):
            converted.append("### " + line[3:])
        elif line.startswith("# "):
            converted.append("## " + line[2:])
        else:
            converted.append(line)
    return (
        f"# {title}\n\n"
        + clean(note)
        + "\n"
        + "\n".join(converted).strip()
        + "\n\n"
    )


