BOOK += section(
    "12",
    "Что такое UNWIND_INFO и его общая идея",
    """
    `UNWIND_INFO` - компактная структура, которая описывает, что prolog функции
    сделал со стеком и nonvolatile-состоянием. Ее задача - не показать исходный
    код и не заменить дизассемблер. Ее задача уже: дать Windows достаточно
    информации, чтобы из context текущей функции восстановить context caller-а.

    Заголовок `UNWIND_INFO` версии 1 занимает четыре байта:

    ```text
    byte 0: Version (3 bits) + Flags (5 bits)
    byte 1: SizeOfProlog
    byte 2: CountOfCodes
    byte 3: FrameRegister (4 bits) + FrameOffset (4 bits)
    ```

    После заголовка идет массив `UNWIND_CODE`. Каждый slot имеет два байта, но
    не каждая логическая операция занимает один slot. Например,
    `UWOP_ALLOC_SMALL` помещается в один slot, а `UWOP_ALLOC_LARGE` требует
    дополнительных operand slots.

    Главная идея: prolog выполняет действия вперед, unwind отменяет их назад.
    Если prolog сделал:

    ```asm
    push rbx
    sub  rsp, 40h
    ```

    то virtual unwind должен понять:

    ```text
    fixed stack allocation = 0x40
    RBX сохранен на стеке
    caller RSP находится выше
    return address лежит там, где caller оставил его после call
    ```

    Поэтому `UNWIND_INFO` - это не "метаданные ради метаданных". Это механика
    восстановления состояния машины. Если структура повреждена, Windows,
    debugger, profiler, crash dump analyzer и reverse engineer могут получить
    неверную картину вызовов.
    """,
)


