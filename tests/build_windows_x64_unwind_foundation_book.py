    """
    Вызов функции на машинном уровне - это передача управления по правилам ABI.
    Caller, вызывающая функция, подготавливает аргументы и выполняет `call`.
    Callee, вызываемая функция, получает управление, выполняет работу и
    возвращается через `ret`.

    Инструкция `call target` на x64 делает две принципиальные вещи. Она
    записывает адрес следующей инструкции на стек и меняет `RIP` на адрес
    `target`. Записанный адрес называется return address. Потом, когда callee
    выполнит `ret`, процессор прочитает этот адрес со стека и продолжит
    выполнение caller-а.

    Но реальная функция почти никогда не ограничивается одним `ret`. Ей нужны
    локальные переменные, место для вызова других функций, возможно сохранение
    `RBX`, `RBP`, `RSI`, `RDI`, `R12`-`R15`. Поэтому в начале функции обычно
    есть prolog. Prolog создает рабочее состояние функции: двигает `RSP`,
    сохраняет регистры, иногда устанавливает frame register. В конце функции
    epilog делает обратное.

    Пример типичной идеи:

    ```asm
    push rbx          ; сохранить nonvolatile-регистр
    sub  rsp, 40h     ; выделить место на стеке
    ...
    add  rsp, 40h     ; вернуть RSP
    pop  rbx          ; восстановить RBX
    ret
    ```

    Если исключение случилось после `push rbx` и `sub rsp, 40h`, обычного
    `ret` еще нет. Windows должна сама понять: чтобы вернуться к caller context,
    надо прибавить к `RSP` выделенный размер, прочитать сохраненный `RBX`,
    найти return address и вычислить новый `RIP`. Она не хочет дизассемблировать
    функцию каждый раз во время исключения. Поэтому компилятор заранее записал
    в `.xdata` компактное описание того, что сделал prolog.

    Stack frame - это именно это состояние активного вызова. В нем нет
    гарантированно красивых границ, но есть правила ABI и metadata, по которым
    Windows может восстановить предыдущий кадр.
    """,
