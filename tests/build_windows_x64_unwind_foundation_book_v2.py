def build() -> str:
    manuscript = INTRO + "\n" + FOUNDATION + "\n"
    for title, intro, sections in PARTS:
        manuscript += chapter(title, intro)
        for number, section_title, body in sections:
            manuscript += h2(number, section_title, body)
    manuscript += clean(
        """
        # Часть II. Углубленные лекции: широкий фундамент вокруг основной линии

        Первая часть книги ведет по твоему плану от исключения до проекта. Вторая часть
        расширяет фундамент: связывает исходный код, процесс загрузки, память, стек,
        PE loader, ABI, decoder, эвристики, dynamic collector, отчетность, validation и
        защиту ВКР. Эти лекции нужны не для раздувания страниц, а чтобы у читателя после
        основной линии появилась толстая техническая подложка: почему каждый байт и
        каждое поле в проекте имеют именно такую роль.
        """
    )
    for title, rel_path in DEEP_SOURCE_FILES:
        manuscript += include_deep_source(title, rel_path)
    manuscript += APPENDICES
    return polish(manuscript)


