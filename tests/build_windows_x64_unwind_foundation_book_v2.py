def include_deep_source(title: str, rel_path: str) -> str:
    source = ROOT / rel_path
    text = polish(source.read_text(encoding="utf-8"))
    converted: list[str] = [f"## {title}", ""]
    for line in text.splitlines():
        if line.startswith("#"):
            stripped = line.lstrip("#").strip()
            if stripped and stripped not in title:
                converted.append(f"### {stripped}")
        else:
            converted.append(line)
    return "\n".join(converted).strip() + "\n\n"


